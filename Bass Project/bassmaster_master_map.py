def normalize_event_name(value: str | None) -> str:
    """Normalize sponsor/series wording so historical title variants can match."""
    if not value:
        return ""

    text = value.lower().replace("&", " and ")
    text = re.sub(r"[^a-z0-9]+", " ", text)
    text = re.sub(
        r"\b(progressive|bass pro shops|academy sports outdoors|academy|"
        r"geico|toyota|st croix|diet mtn dew|mtn dew|presented by|"
        r"bassmaster|elite series|elite|series|tournament|event)\b",
        " ",
        text,
    )
    text = re.sub(r"\b(the|at|of|and|on|presented)\b", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def match_tournament_metadata(
    year,
    scraped_title: str | None,
    period_id: str | None = None,
    legacy_map: dict | None = None,
    minimum_score: float = 0.62,
    ambiguity_margin: float = 0.08,
) -> dict:
    """
    Match a scraped title to the supplied inventory for the same year.

    Returns normalized metadata plus Metadata_Source and Metadata_Match_Score.
    If the title is ambiguous or below threshold, optionally falls back to
    the original (year, periodId) map, clearly marking that fallback.
    """
    year_text = str(year) if year is not None else ""
    title_norm = normalize_event_name(scraped_title)

    candidates = [
        item for item in TOURNAMENT_INVENTORY
        if str(item["year"]) == year_text
    ]

    scored = []
    for item in candidates:
        candidate_norm = normalize_event_name(item["name"])
        if not title_norm or not candidate_norm:
            score = 0.0
        elif title_norm == candidate_norm:
            score = 1.0
        else:
            score = SequenceMatcher(
                None, title_norm, candidate_norm
            ).ratio()

            # Token overlap helps when sponsor words or word order differ.
            title_tokens = set(title_norm.split())
            candidate_tokens = set(candidate_norm.split())
            if title_tokens and candidate_tokens:
                overlap = len(title_tokens & candidate_tokens) / max(
                    len(title_tokens | candidate_tokens), 1
                )
                score = max(score, overlap)

        scored.append((score, item))

    scored.sort(key=lambda pair: pair[0], reverse=True)

    if scored:
        best_score, best_item = scored[0]
        second_score = scored[1][0] if len(scored) > 1 else 0.0
        unambiguous = (best_score - second_score) >= ambiguity_margin

        if best_score >= minimum_score and unambiguous:
            return {
                "clean_name": best_item["name"],
                "location": best_item["location"],
                "dates": best_item["date"],
                "ffs_status": best_item["ffs_status"],
                "metadata_source": "supplied_inventory_title_match",
                "metadata_match_score": round(best_score, 3),
                "metadata_needs_review": False,
            }

    # The period-ID mapping may be useful, but must not be silently treated
    # as verified because periodId is not guaranteed to equal inventory order.
    if legacy_map is not None and period_id is not None:
        legacy = legacy_map.get((year_text, str(period_id)))
        if legacy:
            return {
                "clean_name": legacy.get("clean_name") or scraped_title,
                "location": legacy.get("location", "Unknown Location"),
                "dates": legacy.get("dates"),
                "ffs_status": legacy.get("ffs_status", "Unknown"),
                "metadata_source": "legacy_period_map_fallback_unverified",
                "metadata_match_score": None,
                "metadata_needs_review": True,
            }

    return {
        "clean_name": scraped_title or f"Tournament ID {period_id or 'Unknown'}",
        "location": "Unknown Location",
        "dates": None,
        "ffs_status": "Unknown",
        "metadata_source": "unmatched_scraped_title",
        "metadata_match_score": None,
        "metadata_needs_review": True,
    }


def inventory_summary() -> dict:
    """Return counts useful for checking inventory coverage."""
    years = sorted({item["year"] for item in TOURNAMENT_INVENTORY})
    return {
        "event_count": len(TOURNAMENT_INVENTORY),
        "years": years,
        "events_by_year": {
            year: sum(item["year"] == year for item in TOURNAMENT_INVENTORY)
            for year in years
        },
    }


